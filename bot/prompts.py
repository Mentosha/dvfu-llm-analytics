def build_user_block(user_instruction: str | None) -> str:
    instr = (user_instruction or "").strip()
    if not instr:
        instr = "Никаких особых требований. Сделай общий анализ."
    return (
        "Файл с данными прикреплён к этому сообщению.\n\n"
        "<user_instruction>\n"
        f"{instr}\n"
        "</user_instruction>\n\n"
        "Проанализируй данные, следуя workflow и constraints системной инструкции. "
        "Сгенерируй и выполни Python-код через инструмент Code Execution."
    )


